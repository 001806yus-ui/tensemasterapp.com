// Builds the public previews of the membership lessons (src/data/tensePreviews.ts)
// from the full lessons kept on the server (src/server/premiumTenses.ts).
// Run with: npm run lessons
import { writeFileSync } from 'node:fs';
import { PREMIUM_TENSES } from '../src/server/premiumTenses';
import { toPreview } from '../src/server/lessonPreview';

const body = JSON.stringify(PREMIUM_TENSES.map(toPreview), null, 2);
writeFileSync(new URL('../src/data/tensePreviews.ts', import.meta.url), `// Generated by scripts/build-lesson-previews.ts from src/server/premiumTenses.ts. Do not edit by hand.
import { TenseData } from '../types/index.js';

// What everyone can see of a membership lesson: its name, formula, signal words,
// first example and how many exercises it has. The rest stays on the server.
export const TENSE_PREVIEWS: TenseData[] = ${body};
`);
console.log(`${PREMIUM_TENSES.length} lesson previews written`);
